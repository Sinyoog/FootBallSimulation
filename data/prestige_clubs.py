def prestige_level(country: str, team_name: str) -> int:
    """[2026-07 v2 신설] PRESTIGE_TEAMS에서 그 팀의 명문 등급(3/2/1)을
    찾는다 — 없으면 0. is_prestige()와 마찬가지로 강등 여부와 무관하게
    그 나라의 모든 등급을 다 훑는다."""
    for level, names in PRESTIGE_TEAMS.get(country, {}).items():
        if team_name in names:
            return level
    return 0


def is_prestige(country: str, tier: int, team_name: str) -> bool:
    """[2026-07 버그수정, 신민용 리포트: "명문팀이 강등되는 경우가 너무
    많다"] PRESTIGE_TEAMS는 전부 tier=1 밑에만 정의돼 있는데, 이 함수가
    정확히 그 tier로만 조회하고 있었다 — 그래서 명문팀이 단 한 번이라도
    강등되면(tier != 1) 그 순간부터 is_prestige()가 영원히 False를
    반환했다. _retire_and_replace의 신인 OVR 보정(+2~5)이 강등 즉시
    완전히 끊기고, 이후 신인 목표치는 온전히 '강등된 현재 티어' 기준으로만
    뽑히니 스쿼드가 그 리그 평균으로 수렴해버려 다시 올라올 발판이
    사라지는 게 실측으로 확인됐다(맨유/아스널 등 2부 강등팀 스쿼드
    평균이 강등된 리그 평균과 거의 동일해져 있었음). tier 인자는
    (호출부 하위호환을 위해) 남겨두되, 실제 판정은 그 나라의 모든 tier
    목록을 다 훑어 '팀 이름이 명문팀 리스트 어딘가에 있는지'만 본다 —
    강등되어도 '그 클럽은 원래 명문팀이었다'는 사실 자체는 안 바뀌므로.
    [2026-07 v2] PRESTIGE_TEAMS 숫자 키 의미가 '리그 부수'→'명문 등급'
    으로 바뀌었지만 이 함수는 애초에 그 값 자체를 안 쓰고 있어(키와
    무관하게 전체를 훑음) 이 변경의 영향을 받지 않는다."""
    return prestige_level(country, team_name) > 0


def prestige_weight(country: str, team_name: str) -> float:
    """[2026-07 v2] weighted_team_order에 넘길 팀별 가중치. 명문 등급
    (3/2/1)에 따라 PRESTIGE_WEIGHT_BY_LEVEL에서 찾고, 명문이 아니면
    1.0(가중치 없음 = 일반팀과 동일 확률)."""
    level = prestige_level(country, team_name)
    return PRESTIGE_WEIGHT_BY_LEVEL.get(level, 1.0)


def prestige_fee_mult(country: str, team_name: str) -> float:
    """[2026-08 신설] 이적료 프리미엄 = 레벨 배율 × (1 + (국가열기-1)*가중치).
    레벨0(비명문)이어도 국가 열기 자체는 반영된다(그 나라 이적시장 전체가
    뜨거우면 비명문팀도 어느 정도 영향을 받는 게 자연스러움) — 다만
    가중치가 작아서(0.2) 영향은 제한적."""
    level = prestige_level(country, team_name)
    heat = COUNTRY_FOOTBALL_HEAT.get(country, COUNTRY_FOOTBALL_HEAT_DEFAULT)
    return PRESTIGE_LEVEL_FEE_MULT.get(level, 1.0) * (1 + (heat - 1) * COUNTRY_HEAT_FEE_WEIGHT)


def prestige_salary_mult(country: str, team_name: str) -> float:
    """[2026-08 신설] 연봉 프리미엄 = 레벨 배율 × (1 + (국가열기-1)*가중치).
    이적료보다 레벨 배율 자체도 약하고(1.12 vs 1.25) 국가열기 가중치도
    더 크게 반영되지만(0.4 vs 0.2) 절대적으로는 여전히 이적료보다 약한
    프리미엄이 나온다 — "명문에서 뛰는 것 자체가 보상"이라는 설계 의도."""
    level = prestige_level(country, team_name)
    heat = COUNTRY_FOOTBALL_HEAT.get(country, COUNTRY_FOOTBALL_HEAT_DEFAULT)
    return PRESTIGE_LEVEL_SALARY_MULT.get(level, 1.0) * (1 + (heat - 1) * COUNTRY_HEAT_SALARY_WEIGHT)


