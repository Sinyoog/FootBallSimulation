def weighted_team_order(teams: list) -> list:
    """팀 리스트(각 원소는 dict, 'prestige' bool 키 포함)를 받아 강도 순서
    (0번=가장 강함)를 결정하는 인덱스 순열을 반환한다.

    Efraimidis-Spirakis 가중 무작위 순열 알고리즘 사용: 각 팀에
    key = random()**(1/weight) 를 부여하고 key가 큰 순서로 정렬하면,
    weight가 큰 팀일수록 앞쪽(강한 슬롯)에 나올 확률이 높아지되 무작위성은
    그대로 유지된다 — 완전 고정 배정이 아니라 '확률이 기운 랜덤'이라
    명문팀도 가끔 하위권으로 떨어질 수 있다.
    """
    import random
    n = len(teams)
    keyed = []
    for i, t in enumerate(teams):
        # [2026-07 확장] 'weight'가 직접 주어지면 그걸 우선 쓴다(등급별
        # 차등 지원, prestige_weight() 참고) — 없으면 예전처럼 'prestige'
        # bool만 보고 결정(하위호환). PRESTIGE_WEIGHT가 v2에서 등급별
        # 딕셔너리(PRESTIGE_WEIGHT_BY_LEVEL)로 바뀌어 단일 스칼라가 아니라,
        # bool 하나만 들어오면 등급 정보가 없으므로 중간 등급(2급) 가중치로
        # 폴백한다.
        if "weight" in t:
            w = t["weight"]
        else:
            w = PRESTIGE_WEIGHT_BY_LEVEL[2] if t.get("prestige") else 1.0
        key = random.random() ** (1.0 / w)
        keyed.append((key, i))
    keyed.sort(key=lambda x: -x[0])
    return [i for _, i in keyed]