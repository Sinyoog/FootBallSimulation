    # [2026-07 신설, 신민용 지적: "'리그 전체'와 '상위 몇 팀'을 구분해야
    # 한다 — 알힐랄/알나스르/알이티하드/알아흘리 4강은 다른 사우디팀과
    # 완전히 다른 급인데 지금은 '사우디 전체'로 뭉뚱그려진다"] 오일머니가
